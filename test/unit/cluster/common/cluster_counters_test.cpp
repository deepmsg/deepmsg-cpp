TEST(ClusterCountersTest, clusterIdKeyIsFourLittleEndianBytes)
{
    const auto key = cluster_counter_key(0x01020304);
    ASSERT_EQ(4U, key.size());
    EXPECT_EQ(0x04, key[0]);
    EXPECT_EQ(0x03, key[1]);
    EXPECT_EQ(0x02, key[2]);
    EXPECT_EQ(0x01, key[3]);

    const auto negative = cluster_counter_key(-2);
    EXPECT_EQ(0xFE, negative[0]);
    EXPECT_EQ(0xFF, negative[1]);
    EXPECT_EQ(0xFF, negative[2]);
    EXPECT_EQ(0xFF, negative[3]);
}

TEST(ClusterCountersTest, serviceCounterKeyIsClusterIdThenServiceId)
{
    const auto key = service_counter_key(0x01020304, 0x05060708);
    ASSERT_EQ(8U, key.size());
    EXPECT_EQ(0x04, key[0]);
    EXPECT_EQ(0x03, key[1]);
    EXPECT_EQ(0x02, key[2]);
    EXPECT_EQ(0x01, key[3]);
    EXPECT_EQ(0x08, key[4]);
    EXPECT_EQ(0x07, key[5]);
    EXPECT_EQ(0x06, key[6]);
    EXPECT_EQ(0x05, key[7]);
}

TEST(ClusterCountersTest, labelsMatchTheReferenceFormat)
{
    EXPECT_EQ("Cluster commit-pos: - clusterId=7", cluster_counter_label("Cluster commit-pos:", 7));
    EXPECT_EQ("Cluster Container Errors - clusterId=3 serviceId=2",
              service_counter_label("Cluster Container Errors", 3, 2));
    EXPECT_EQ(" version=1.54.0 commit=abcdef0", version_info("1.54.0", "abcdef0"));
}

